"""PostgreSQL connections, schema setup and atomic write transactions."""
from contextlib import contextmanager

import click
import psycopg
from flask import current_app, g
from psycopg.rows import dict_row

SCHEMA = """
CREATE TABLE IF NOT EXISTS halls (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE,
 amenity BIGINT NOT NULL CHECK(amenity>=0), amenities TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS rooms (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, hall_id INTEGER NOT NULL REFERENCES halls(id),
 number TEXT NOT NULL, capacity INTEGER NOT NULL CHECK(capacity BETWEEN 1 AND 4),
 rent BIGINT NOT NULL CHECK(rent>=0), UNIQUE(hall_id,number));
CREATE TABLE IF NOT EXISTS students (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, roll TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
 address TEXT NOT NULL, mobile TEXT NOT NULL, parent_phone TEXT NOT NULL,
 photo TEXT NOT NULL, admission_note TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL,
 role TEXT NOT NULL, hall_id INTEGER REFERENCES halls(id),
 student_id INTEGER UNIQUE REFERENCES students(id));
CREATE TABLE IF NOT EXISTS allocations (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL UNIQUE REFERENCES students(id),
 room_id INTEGER NOT NULL REFERENCES rooms(id), created TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS mess_charges (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL REFERENCES students(id),
 month TEXT NOT NULL, amount BIGINT NOT NULL CHECK(amount>=0),
 UNIQUE(student_id,month));
CREATE TABLE IF NOT EXISTS bills (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL REFERENCES students(id),
 hall_id INTEGER NOT NULL REFERENCES halls(id), month TEXT NOT NULL,
 rent BIGINT NOT NULL CHECK(rent>=0), mess BIGINT NOT NULL CHECK(mess>=0),
 amenity BIGINT NOT NULL CHECK(amenity>=0), created TEXT NOT NULL,
 UNIQUE(student_id,month));
CREATE TABLE IF NOT EXISTS payments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, bill_id INTEGER NOT NULL REFERENCES bills(id),
 rent BIGINT NOT NULL CHECK(rent>=0), mess BIGINT NOT NULL CHECK(mess>=0),
 amenity BIGINT NOT NULL CHECK(amenity>=0), created TEXT NOT NULL,
 user_id INTEGER NOT NULL REFERENCES users(id),
 CHECK(rent+mess+amenity>0));
CREATE TABLE IF NOT EXISTS complaints (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id INTEGER NOT NULL REFERENCES students(id),
 hall_id INTEGER NOT NULL REFERENCES halls(id), category TEXT NOT NULL,
 description TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'Open',
 atr TEXT NOT NULL DEFAULT '', created TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS settlements (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, hall_id INTEGER NOT NULL REFERENCES halls(id),
 month TEXT NOT NULL, amount BIGINT NOT NULL CHECK(amount>0),
 manager TEXT NOT NULL, cheque TEXT NOT NULL UNIQUE, created TEXT NOT NULL,
 acknowledged INTEGER NOT NULL DEFAULT 0, acknowledged_at TEXT,
 UNIQUE(hall_id,month));
CREATE TABLE IF NOT EXISTS audit (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER REFERENCES users(id),
 action TEXT NOT NULL, detail TEXT NOT NULL, created TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS documents (
 name TEXT PRIMARY KEY,
 content_type TEXT NOT NULL,
 data BYTEA NOT NULL CHECK(octet_length(data) <= 4194304));
"""


def get_db():
    """Reuse one PostgreSQL connection during the current request."""
    if 'db' not in g:
        g.db = psycopg.connect(
            current_app.config['DATABASE_URL'],
            autocommit=True,
            row_factory=dict_row,
            prepare_threshold=None,
            connect_timeout=15,
            options=current_app.config.get('DATABASE_OPTIONS', ''),
        )
    return g.db


@contextmanager
def transaction():
    """Commit writes together, or roll them all back on failure.

    A transaction-level advisory lock serialises this small app's writes across
    Vercel instances, protecting room capacity, payments and closed collections.
    """
    db = get_db()
    with db.transaction():
        db.execute('SELECT pg_advisory_xact_lock(690312)')
        yield db


def close_db(error=None):
    db = g.pop('db', None)
    if db is not None:
        db.close()


def init_db():
    """Create missing tables without changing existing records."""
    with transaction() as db:
        for statement in SCHEMA.split(';'):
            if statement.strip():
                db.execute(statement)


def register_commands(app):
    @app.cli.command('init-db')
    def init_db_command():
        """Create the PostgreSQL tables."""
        init_db()
        click.echo('PostgreSQL tables are ready.')

    @app.cli.command('create-admin')
    @click.option('--username', prompt=True, default='admin')
    @click.password_option()
    def create_admin(username, password):
        """Create an administrator without demo accounts."""
        from werkzeug.security import generate_password_hash

        if not username.strip() or len(password) < 8:
            raise click.ClickException('Enter a username and a password of at least 8 characters.')
        init_db()
        try:
            with transaction() as db:
                db.execute(
                    "INSERT INTO users(username,password_hash,role) VALUES(%s,%s,'admin')",
                    (username.strip(), generate_password_hash(password)),
                )
        except psycopg.IntegrityError:
            raise click.ClickException('That username already exists.') from None
        click.echo('Administrator account created.')
